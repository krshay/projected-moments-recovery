function experiment = gd_run_josh_baseline_restarts(problem,options)
%GD_RUN_JOSH_BASELINE_RESTARTS Josh's objective with his initialization rules.

restart_count = options.restart_count;
seed = options.seed;
optimizer_options = options.optimizer;
initialization = options.initialization;
restarts = repmat(empty_restart(),restart_count,1);
experiment_timer = tic;
fprintf('\n%s: %d restarts, no regularizer; A0,A1 fixed to truth\n', ...
    problem.name,restart_count);
for restart = 1:restart_count
    x0 = original_initialization( ...
        problem,seed+restart-1,initialization,options);
    objective = @(x) gd_third_moment_objective(x,problem);
    metric = @(x) metric_from_x(x,problem);
    [x,objective_value,optimizer_info] = ...
        gd_minimize(objective,x0,optimizer_options,metric);
    [~,gradient] = objective(x);
    estimate = gd_decode_parameters(x,problem.parameterization,problem.base);
    errors = gd_coefficient_errors(estimate,problem);
    success = errors.relative_error < problem.success_threshold;
    restarts(restart) = struct('restart',restart,'seed',seed+restart-1, ...
        'x0',x0,'x',x,'coefficients_estimate',estimate, ...
        'objective',objective_value,'relative_error',errors.relative_error, ...
        'optimized_band_error',errors.optimized_band_error, ...
        'error_to_truth',errors.error_to_truth, ...
        'error_to_reflection',errors.error_to_reflection, ...
        'band_relative_error',errors.band_relative_error, ...
        'iterations',optimizer_info.iterations, ...
        'gradient_norm',norm(gradient), ...
        'runtime_seconds',optimizer_info.runtime_seconds, ...
        'history',optimizer_info.history,'optimizer',optimizer_info.optimizer, ...
        'exitflag',optimizer_info.exitflag, ...
        'reached_global_solution',success, ...
        'reality_defect',gd_reality_defect(estimate, ...
            problem.L_max,problem.support));
    fprintf(['  restart %d: loss=%.3e, error=%.3e, ||g||=%.3e, ', ...
        'iterations=%d, runtime=%.2fs%s\n'],restart,objective_value, ...
        errors.relative_error,norm(gradient),optimizer_info.iterations, ...
        optimizer_info.runtime_seconds,success_label(success));
end
[best_error,best_restart] = min([restarts.relative_error]);
experiment = struct('name',problem.name,'method','Josh baseline', ...
    'objective','normalized projected third-moment residual only', ...
    'moment_source',problem.moment_source,'fixed_bands',[0,1], ...
    'optimized_bands',2:problem.L_max,'L_max',problem.L_max, ...
    'support',problem.support,'restarts',restarts, ...
    'success_count',sum([restarts.reached_global_solution]), ...
    'best_restart',best_restart,'best_relative_error',best_error, ...
    'runtime_seconds',toc(experiment_timer), ...
    'coefficients_true',problem.coefficients_true, ...
    'coefficients_reflected',problem.coefficients_reflected, ...
    'disclaimer',problem.disclaimer);
end

function x0 = original_initialization(problem,seed,mode,options)
rng(seed);
switch lower(mode)
    case 'synthetic'
        % Exact match to Josh's synthetic script: unscaled N(0,1) real DOF.
        x0 = randn(size(problem.parameterization,1),1);
    case 'real'
        % Exact match to Josh's real script: per-band truth-scale Gaussian.
        band_scale = zeros(1,problem.L_max+1);
        for l = 2:problem.L_max
            band = problem.coefficients_true(1:problem.support(l+1), ...
                gd_band_indices(l));
            band_scale(l+1) = norm(band,'fro')/sqrt( ...
                problem.support(l+1)*(2*l+1));
        end
        scale = zeros(size(problem.parameterization,1),1);
        for index = 1:size(problem.parameterization,1)
            scale(index) = band_scale(problem.parameterization(index,2)+1);
        end
        x0 = randn(size(scale)).*scale;
    case 'near_truth'
        % Josh's standalone sanity test: multiplicative perturbation of truth.
        perturbation = options.perturbation;
        x0 = problem.x_true.*(1+perturbation*randn(size(problem.x_true)));
    otherwise
        error('Unknown Josh initialization mode: %s',mode);
end
end

function metric = metric_from_x(x,problem)
estimate = gd_decode_parameters(x,problem.parameterization,problem.base);
metric = gd_coefficient_errors(estimate,problem);
end

function result = empty_restart()
result = struct('restart',[],'seed',[],'x0',[],'x',[], ...
    'coefficients_estimate',[],'objective',[],'relative_error',[], ...
    'optimized_band_error',[],'error_to_truth',[], ...
    'error_to_reflection',[],'band_relative_error',[],'iterations',[], ...
    'gradient_norm',[],'runtime_seconds',[],'history',[],'optimizer',[], ...
    'exitflag',[],'reached_global_solution',[],'reality_defect',[]);
end

function label = success_label(success)
if success
    label = ' -> recovered';
else
    label = '';
end
end
