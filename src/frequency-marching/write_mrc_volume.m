function write_mrc_volume(path,volume)
%WRITE_MRC_VOLUME Write a real 3-D array as little-endian mode-2 MRC.

assert(isreal(volume) && ndims(volume) == 3,'Volume must be a real 3-D array.');
volume = single(volume);
dimensions = size(volume);
fid = fopen(path,'w','l');
assert(fid >= 0,'Could not open %s for writing.',path);
cleanup = onCleanup(@() fclose(fid));

fwrite(fid,int32([dimensions,2]),'int32');             % NX,NY,NZ,MODE
fwrite(fid,int32([0,0,0]),'int32');                    % starts
fwrite(fid,int32(dimensions),'int32');                 % sampling grid
fwrite(fid,single(dimensions),'float32');              % cell lengths
fwrite(fid,single([90,90,90]),'float32');              % cell angles
fwrite(fid,int32([1,2,3]),'int32');                    % MAPC,MAPR,MAPS
fwrite(fid,single([min(volume(:)),max(volume(:)), ...
    mean(volume(:))]),'float32');
fwrite(fid,int32([0,0]),'int32');                      % ISPG,NSYMBT
fwrite(fid,zeros(1,25,'int32'),'int32');               % extra
fwrite(fid,single([0,0,0]),'float32');                 % origin
fwrite(fid,uint8('MAP '),'uint8');
fwrite(fid,uint8([68,65,0,0]),'uint8');                % little-endian stamp
fwrite(fid,single(std(double(volume(:)),1)),'float32');
fwrite(fid,int32(1),'int32');
label = uint8(sprintf('%-80s','Generated by projected-moments-recovery'));
fwrite(fid,label(1:80),'uint8');
fwrite(fid,zeros(1,720,'uint8'),'uint8');
assert(ftell(fid) == 1024,'Internal error constructing MRC header.');
fwrite(fid,volume(:),'float32');
end
