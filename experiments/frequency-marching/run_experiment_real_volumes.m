function summary = run_experiment_real_volumes(config)
%RUN_EXPERIMENT_REAL_VOLUMES Noiseless failure/success on TRPV1 and 80S.

n_volumes = numel(config.real_volumes);
unmodified_error = nan(1,n_volumes);
modified_error = nan(1,n_volumes);
unmodified_global_error = nan(1,n_volumes);
modified_global_error = nan(1,n_volumes);
unmodified_runtime_seconds = nan(1,n_volumes);
modified_runtime_seconds = nan(1,n_volumes);
condition_before = false(1,n_volumes);
condition_after = false(1,n_volumes);
details = cell(1,n_volumes);
condition_table = table();
if exist(config.volume_results_dir,'dir') ~= 7
    mkdir(config.volume_results_dir);
end

options = struct('use_analytical_p3',true,'enable_backfill',true, ...
    'verify_analytical',false,'verbose',true,'rng_seed',config.seed);

for idx = 1:n_volumes
    volume = config.real_volumes(idx);
    fprintf('\n============================================================\n');
    fprintf(' Real-volume experiment: %s\n',volume.name);
    fprintf('============================================================\n');
    cache_path = fullfile(config.processed_dir, ...
        sprintf('%s_L%d_grid%d_v2_fourier_bessel.mat',lower(volume.name), ...
        config.volume_options.L_max,config.volume_options.grid_size));
    if exist(cache_path,'file') == 2
        cached = load(cache_path,'a','available_shells','metadata');
        a = cached.a;
        available_shells = cached.available_shells;
        metadata = cached.metadata;
    else
        [a,available_shells,metadata] = ...
            expand_real_volume_fourier_bessel(volume.path,config.volume_options);
        save(cache_path,'a','available_shells','metadata','-v7.3');
    end

    before = check_decay_by_three(available_shells);
    condition_before(idx) = before.satisfies_decay_by_three;
    fprintf('Unmodified supports: [%s]\n',num2str(available_shells));
    fprintf('Decay-by-3 satisfied: %d (minimum parity gap %g)\n', ...
        before.satisfies_decay_by_three,before.minimum_parity_gap);
    [a_decay,S_decay,~,after] = enforce_decay_by_three( ...
        a,available_shells,config.terminal_shells);
    condition_after(idx) = after.satisfies_decay_by_three;
    fprintf('Solver support:      [%s]\n',num2str(S_decay));

    % Use the same theorem-compatible solver support in both runs. The
    % unmodified volume then contains an out-of-model tail, whereas the
    % modified volume differs only by zeroing that tail.
    reconstruction_timer = tic;
    unmodified = frequency_marching_recovery(a,S_decay,options);
    unmodified_runtime_seconds(idx) = toc(reconstruction_timer);
    fprintf('Unmodified reconstruction runtime: %.3f s\n', ...
        unmodified_runtime_seconds(idx));

    reconstruction_timer = tic;
    modified = frequency_marching_recovery(a_decay,S_decay,options);
    modified_runtime_seconds(idx) = toc(reconstruction_timer);
    fprintf('Decay-by-3 reconstruction runtime: %.3f s\n', ...
        modified_runtime_seconds(idx));

    file_stem = lower(volume.name);
    mrc_files = struct( ...
        'unmodified_true',fullfile(config.volume_results_dir, ...
            sprintf('%s_unmodified_true.mrc',file_stem)), ...
        'unmodified_reconstruction',fullfile(config.volume_results_dir, ...
            sprintf('%s_unmodified_reconstruction.mrc',file_stem)), ...
        'decay_true',fullfile(config.volume_results_dir, ...
            sprintf('%s_decay_by_three_true.mrc',file_stem)), ...
        'decay_reconstruction',fullfile(config.volume_results_dir, ...
            sprintf('%s_decay_by_three_reconstruction.mrc',file_stem)));
    write_mrc_volume(mrc_files.unmodified_true, ...
        reconstruct_fourier_bessel_volume(a,metadata));
    write_mrc_volume(mrc_files.unmodified_reconstruction, ...
        reconstruct_fourier_bessel_volume(unmodified.a_est,metadata));
    write_mrc_volume(mrc_files.decay_true, ...
        reconstruct_fourier_bessel_volume(a_decay,metadata));
    write_mrc_volume(mrc_files.decay_reconstruction, ...
        reconstruct_fourier_bessel_volume(modified.a_est,metadata));

    condition_table = [condition_table; add_condition_context( ...
        unmodified.condition_numbers,volume.name,'unmodified')]; %#ok<AGROW>
    condition_table = [condition_table; add_condition_context( ...
        modified.condition_numbers,volume.name,'decay_by_three')]; %#ok<AGROW>

    unmodified_error(idx) = unmodified.recovered_region_error;
    modified_error(idx) = modified.recovered_region_error;
    unmodified_global_error(idx) = unmodified.global_relative_error;
    modified_global_error(idx) = modified.global_relative_error;
    assert(~condition_before(idx), ...
        '%s unexpectedly satisfies decay-by-3 before modification.',volume.name);
    assert(condition_after(idx), ...
        '%s does not satisfy decay-by-3 after modification.',volume.name);
    assert(unmodified_error(idx) > config.noiseless_failure_floor, ...
        '%s unmodified run did not exhibit the expected failure.',volume.name);
    assert(modified_error(idx) < config.noiseless_success_tolerance, ...
        '%s modified run error %.3e exceeds the noiseless tolerance.', ...
        volume.name,modified_error(idx));
    details{idx} = struct('metadata',metadata,'support_before',available_shells, ...
        'support_after',S_decay,'diagnostic_before',before, ...
        'diagnostic_after',after,'unmodified',unmodified,'modified',modified, ...
        'mrc_files',mrc_files);
end

summary = struct('names',{ {config.real_volumes.name} }, ...
    'unmodified_error',unmodified_error,'modified_error',modified_error, ...
    'unmodified_global_error',unmodified_global_error, ...
    'modified_global_error',modified_global_error, ...
    'unmodified_runtime_seconds',unmodified_runtime_seconds, ...
    'modified_runtime_seconds',modified_runtime_seconds, ...
    'total_reconstruction_runtime_seconds', ...
        unmodified_runtime_seconds+modified_runtime_seconds, ...
    'condition_before',condition_before,'condition_after',condition_after, ...
    'condition_numbers',condition_table,'details',{details});
save(fullfile(config.results_dir,'results_real_volumes_noiseless.mat'), ...
    'summary','config','-v7.3');
writetable(condition_table,fullfile(config.results_dir, ...
    'condition_numbers_real_volumes.csv'));
runtime_table = table({config.real_volumes.name}.', ...
    unmodified_runtime_seconds.',modified_runtime_seconds.', ...
    (unmodified_runtime_seconds+modified_runtime_seconds).', ...
    'VariableNames',{'molecule','unmodified_seconds', ...
    'decay_by_three_seconds','total_seconds'});
writetable(runtime_table,fullfile(config.results_dir, ...
    'runtime_real_volumes.csv'));

figure('Color','w');
bar([unmodified_error(:),modified_error(:)]);
set(gca,'YScale','log','XTick',1:n_volumes, ...
    'XTickLabel',{config.real_volumes.name});
ylabel('Relative error on marched shells');
legend({'Unmodified','Decay-by-3 enforced'},'Location','best');
grid on;
apply_publication_style(gcf);
exportgraphics(gcf,fullfile(config.figures_dir, ...
    'frequency_marching_real_volumes.pdf'),'ContentType','vector');
end

function contextual = add_condition_context(condition_numbers,molecule,variant)
contextual = condition_numbers;
contextual.molecule = repmat({molecule},height(contextual),1);
contextual.signal_variant = repmat({variant},height(contextual),1);
contextual = movevars(contextual,{'molecule','signal_variant'},'Before',1);
end
