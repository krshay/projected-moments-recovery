function config = josh_baseline_config(repo_root)
%JOSH_BASELINE_CONFIG Small exact-P3 experiments using Josh's method alone.

config = struct();
config.repo_root = repo_root;
config.seed = 42;
config.output_root = fullfile(repo_root,'results','gradient-descent', ...
    'josh-baseline');
timestamp = datestr(now,'yyyy-mm-dd_HH-MM-SS');
config.run_dir = unique_run_dir(fullfile(config.output_root,timestamp));
config.config_dir = fullfile(config.run_dir,'config');
config.data_dir = fullfile(config.run_dir,'data');
config.figures_dir = fullfile(config.run_dir,'figures');
config.logs_dir = fullfile(config.run_dir,'logs');

config.synthetic = struct('L_max',5,'shell_count',12,'seed',42, ...
    'restart_count',5,'success_threshold',1e-5, ...
    'optimizer',struct('method','auto','max_iterations',600, ...
        'optimality_tolerance',1e-10,'step_tolerance',1e-14, ...
        'function_tolerance',1e-16,'display','off'));

config.real = struct('restart_count',5,'radial_count',12, ...
    'success_threshold',1e-4, ...
    'optimizer',struct('method','auto','max_iterations',200, ...
        'optimality_tolerance',1e-10,'step_tolerance',1e-14, ...
        'function_tolerance',1e-16,'display','off'), ...
    'volume_options',struct('L_max',5,'grid_size',31,'rho_max',pi, ...
        'basis_mode','manual','manual_shells',[12,12,12,12,12,12]));
config.real_volumes = struct( ...
    'name',{'TRPV1','80S'}, ...
    'path',{fullfile(repo_root,'data','raw','vol_TRPV1_true.mrc'), ...
            fullfile(repo_root,'data','raw','vol_80S_true.mrc')});
end

function directory = unique_run_dir(candidate)
directory = candidate;
suffix = 2;
while exist(directory,'dir') == 7
    directory = sprintf('%s_%02d',candidate,suffix);
    suffix = suffix+1;
end
end
